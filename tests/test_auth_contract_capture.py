def test_email_login(client):
    _rider_with_password()

    response = client.post('/api/v1/auth/email/login/', {
        'email': 'contract-rider@example.test', 'password': PASSWORD,
    }, format='json')
    assert response.status_code == 200
    body = _capture('auth_login_email', response,
                    note='POST /auth/email/login/ — email + password')

    data = body['data']
    # Identical envelope to the OTP login, which is what lets a client swap
    # one for the other without touching the rest of its code.
    assert set(data) == {'token', 'refresh_token', 'user'}


def test_email_login_rejected(client):
    _rider_with_password()
    response = client.post('/api/v1/auth/email/login/', {
        'email': 'contract-rider@example.test', 'password': 'wrong',
    }, format='json')
    assert response.status_code == 401
    body = _capture('auth_login_email_rejected', response,
                    note='POST /auth/email/login/ — wrong password; the SAME '
                         'body is returned for an unknown address')

    assert body['error']['code'] == 'AUTH_INVALID_CREDENTIALS'
    assert body['error']['message'] == 'Invalid email or password.'


