def test_token_refresh(client):
    user = _rider_with_password('contract-refresh@example.test')
    login = client.post('/api/v1/auth/email/login/', {
        'email': user.email, 'password': PASSWORD,
    }, format='json').json()

    response = client.post('/api/v1/auth/refresh/', {
        'refresh_token': login['data']['refresh_token'],
    }, format='json')
    assert response.status_code == 200
    body = _capture('auth_refresh', response,
                    note='POST /auth/refresh/ — rotates the pair')

    data = body['data']
    assert 'token' in data, 'refresh returns `token`, not `access`'
    assert 'access' not in data, (
        'the driver app read `access` here too, so every session died at the '
        '15-minute access-token lifetime'
    )


def test_logout(client):
    user = _rider_with_password('contract-logout@example.test')
    login = client.post('/api/v1/auth/email/login/', {
        'email': user.email, 'password': PASSWORD,
    }, format='json').json()['data']

    client.credentials(HTTP_AUTHORIZATION=f'Bearer {login["token"]}')
    response = client.post('/api/v1/auth/logout/', {
        'refresh_token': login['refresh_token'],
    }, format='json')

    _capture('auth_logout', response, note='POST /auth/logout/')
    assert response.status_code in (200, 205)


