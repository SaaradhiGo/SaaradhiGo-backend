"""Capture the auth API's REAL responses, and publish them as a contract.

WHY THIS FILE EXISTS
--------------------
The driver app read `data['access']` and `data['refresh']` from the login and
refresh responses. The server sends `token` and `refresh_token`. So login
always threw and refresh always failed — **no driver could sign in** — and
nothing caught it, because the app's own tests built fixtures using the same
wrong key names the app used. The tests and the code agreed with each other
and both disagreed with the server.

A fixture written by hand proves only that the hand that wrote it was
consistent. So these tests drive the real views through Django's test client,
assert the contract, and then WRITE THE ACTUAL RESPONSE BODIES to
`contracts/auth_contracts.json`. Both Flutter apps load that file in their own
tests and feed it through their real parsing code.

That makes the loop closed: if a view's response shape changes, this file
regenerates, the apps' tests fail against the new shape, and somebody has to
look. Nobody can "fix" an app test by editing a fixture to match the app.

Regenerate with:

    pytest tests/test_auth_contract_capture.py

and copy the result into each app:

    cp contracts/auth_contracts.json ../SaaradhiGo-mobile/test/contracts/
    cp contracts/auth_contracts.json ../SaaradhiGo-driver/test/contracts/

The file is committed on purpose: it is evidence, and a diff on it is the
review signal that an API contract moved.
"""

import json
import pathlib

import pytest
from django.contrib.auth import get_user_model
from django.test import override_settings
from rest_framework.test import APIClient

from servers.auth_user.password_views import _uid, reset_tokens
from tests.contract_normalise import normalise

pytestmark = pytest.mark.django_db

User = get_user_model()

CONTRACT_PATH = (
    pathlib.Path(__file__).resolve().parent.parent / 'contracts'
    / 'auth_contracts.json'
)

TEST_PHONE = '+919999000001'
TEST_OTP = '100001'
PASSWORD = 'Cadence-Harbour-74'
NEW_PASSWORD = 'Lantern-Meadow-91'

# Captured during the run and written out at the end.
_captured = {}


def _capture(name, response, *, note):
    """Record one real response: status, and the body the server produced."""
    body = response.json() if response.content else None
    _captured[name] = {
        'note': note,
        'status_code': response.status_code,
        # Timestamps and JWTs are replaced with fixed, valid stand-ins so a
        # run that changed nothing writes a file identical to the committed
        # one. See tests/contract_normalise.py.
        'body': normalise(body),
    }
    return body


@pytest.fixture(scope='module', autouse=True)
def _write_contract_file():
    yield
    if not _captured:
        return
    CONTRACT_PATH.parent.mkdir(parents=True, exist_ok=True)
    CONTRACT_PATH.write_text(
        json.dumps(
            {
                '_README': (
                    'GENERATED by tests/test_auth_contract_capture.py from '
                    'real responses. Do not edit by hand -- regenerate. The '
                    'rider and driver apps assert their parsing against this.'
                ),
                'endpoints': dict(sorted(_captured.items())),
            },
            indent=2,
            sort_keys=False,
        )
        + '\n',
        encoding='utf-8',
    )


@pytest.fixture
def client():
    return APIClient()


def _rider_with_password(email='contract-rider@example.test'):
    from django.utils import timezone
    user = User(phone_number='+919820999001', username='contract-rider',
                email=email, role='rider')
    user.set_password(PASSWORD)
    user.email_verified_at = timezone.now()
    user.save()
    return user


# ---------------------------------------------------------------------------
# Mobile OTP login
# ---------------------------------------------------------------------------

@override_settings(TEST_PHONE_NUMBERS={TEST_PHONE: TEST_OTP})
def test_otp_request_and_login(client):
    otp_response = client.post('/api/v1/auth/otp/', {
        'phone_number': TEST_PHONE, 'role': 'rider',
    }, format='json')
    assert otp_response.status_code == 200
    _capture('auth_otp_request', otp_response,
             note='POST /auth/otp/ — issues the OTP; test phones skip SNS')

    response = client.post('/api/v1/auth/login/', {
        'phone_number': TEST_PHONE, 'otp': TEST_OTP,
    }, format='json')
    assert response.status_code == 200
    body = _capture('auth_login_otp', response,
                    note='POST /auth/login/ — phone + OTP')

    # The contract both apps depend on, asserted here so a change is caught
    # at the source rather than in a client.
    data = body['data']
    assert 'token' in data, 'the access token key is `token`'
    assert 'refresh_token' in data, 'the refresh token key is `refresh_token`'
    assert 'access' not in data, (
        'the server does NOT send `access` — the driver app read this key and '
        'could never log in'
    )
    assert 'refresh' not in data
    assert data['user']['phone_number'] == TEST_PHONE


