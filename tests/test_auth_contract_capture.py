def test_forgot_password(client):
    _rider_with_password('contract-forgot@example.test')

    response = client.post('/api/v1/auth/password/forgot/', {
        'email': 'contract-forgot@example.test',
    }, format='json')
    assert response.status_code == 200
    known = _capture('auth_password_forgot', response,
                     note='POST /auth/password/forgot/ — always 200')
    known = response.json()
    known_status = response.status_code

    unknown_response = client.post('/api/v1/auth/password/forgot/', {
        'email': 'nobody-at-all@example.test',
    }, format='json')
    unknown = unknown_response.json()

    # The property that matters: a client cannot tell these apart, so it
    # cannot be used to find out who has an account.
    #
    # `meta.timestamp` is excluded -- every response carries one and the two
    # calls are milliseconds apart. Comparing it would fail for a reason that
    # has nothing to do with enumeration.
    assert unknown_response.status_code == known_status
    assert {k: v for k, v in known.items() if k != 'meta'} ==            {k: v for k, v in unknown.items() if k != 'meta'}


def test_password_reset(client):
    user = _rider_with_password('contract-reset@example.test')

    response = client.post('/api/v1/auth/password/reset/', {
        'uid': _uid(user),
        'token': reset_tokens.make_token(user),
        'new_password': NEW_PASSWORD,
    }, format='json')
    assert response.status_code == 200
    _capture('auth_password_reset', response,
             note='POST /auth/password/reset/ — single-use token')

    user.refresh_from_db()
    assert user.check_password(NEW_PASSWORD)


