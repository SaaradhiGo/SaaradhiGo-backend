def test_role_based_access(client):
    rider = _rider_with_password('contract-rbac@example.test')
    login = client.post('/api/v1/auth/email/login/', {
        'email': rider.email, 'password': PASSWORD,
    }, format='json').json()['data']

    client.credentials(HTTP_AUTHORIZATION=f'Bearer {login["token"]}')

    # A rider holding a valid token must not reach an operator endpoint.
    response = client.post('/api/v1/auth/admin/invite/', {
        'email': 'escalation@example.test', 'role': 'admin',
    }, format='json')

    assert response.status_code in (401, 403)
    _capture('auth_rbac_rider_denied_admin', response,
             note='POST /auth/admin/invite/ as a RIDER — must be refused')
    assert not User.objects.filter(email='escalation@example.test').exists()


def test_anonymous_is_denied(client):
    response = client.get('/api/v1/auth/profile/')
    assert response.status_code in (401, 403)
    _capture('auth_profile_anonymous_denied', response,
             note='GET /auth/profile/ with no token')
